export const lessons = lessonSeeds.map(buildLesson) satisfies Lesson[];

export const lessonsById = Object.fromEntries(
  lessons.map((lesson) => [lesson.id, lesson]),
) as Record<string, Lesson>;

export const lessonsByLanguageId = lessons.reduce(
  (groups, lesson) => {
    groups[lesson.languageId] = [...(groups[lesson.languageId] ?? []), lesson];
    return groups;
  },
  {} as Partial<Record<LanguageId, Lesson[]>>,
);

function buildLesson(seed: LessonSeed): Lesson {
  const mainVocabulary = seed.vocabulary[0];
  const mainPhrase = seed.phrases[0];
  const languageName = languageNames[seed.languageId];
  const pedagogy = lessonPedagogyById[seed.id];

  // For migrated (5-phase) lessons, the practiced items ARE the chunks — so the
  // audio screen practices all of them and screens display the real phrases.
  // Legacy lessons keep their original 3-word vocabulary.
  const vocabulary: VocabularyItem[] = pedagogy
    ? pedagogy.targetChunks.map((chunk) => ({
        id: chunk.id,
        term: chunk.text,
        translation: chunk.translation,
        pronunciation: chunk.pronunciation ?? "",
      }))
    : seed.vocabulary;

  return {
    id: seed.id,
    unitId: seed.unitId,
    languageId: seed.languageId,
    title: seed.title,
    description: pedagogy?.canDo ?? seed.description,
    imageKey: seed.imageKey,
    xpReward: seed.xpReward ?? 10,
    estimatedMinutes: seed.estimatedMinutes ?? (pedagogy ? 12 : 3),
    ...(pedagogy ? { pedagogy } : {}),
    goals: [
      {
        id: `${seed.id}-goal-main`,
        title: seed.goalTitle,
        description: seed.goalDescription,
      },
      {
        id: `${seed.id}-goal-say-it`,
        title: "Say the key phrase",
        description: `Practice: ${mainPhrase.text}`,
      },
    ],
    vocabulary,
    phrases: seed.phrases,
    activities: [
      {
        id: `${seed.id}-vocab-${mainVocabulary.id}`,
        type: "vocabulary",
        prompt: `What does ${mainVocabulary.term} mean?`,
        answer: mainVocabulary.translation,
        vocabularyId: mainVocabulary.id,
      },
      {
        id: `${seed.id}-choice-${mainPhrase.id}`,
        type: "multiple-choice",
        prompt: `Choose the meaning of ${mainPhrase.text}`,
        answer: mainPhrase.translation,
        phraseId: mainPhrase.id,
        options: [
          { id: "a", text: seed.wrongAnswers[0], isCorrect: false },
          { id: "b", text: mainPhrase.translation, isCorrect: true },
          { id: "c", text: seed.wrongAnswers[1], isCorrect: false },
        ],
      },
      {
        id: `${seed.id}-speaking-${mainPhrase.id}`,
        type: "speaking",
        prompt: `Say: ${mainPhrase.text}`,
        answer: mainPhrase.text,
        phraseId: mainPhrase.id,
      },
    ],
    aiTeacherPrompt: {
      mode:
        seed.imageKey === "lessonCafe" || seed.imageKey === "lessonGreetings"
          ? "vision-agent-audio"
          : "audio",
      scenario: seed.scenario,
      voiceStyle:
        "Warm, upbeat, and human, like an encouraging friend. Short sentences, natural contractions, a smile in the voice, and a pause so the learner can repeat.",
      systemPrompt: `You're Duo, a friendly ${languageName} teacher. This lesson has exactly ${seed.vocabulary.length} words to teach, in this order: ${seed.vocabulary.map((v) => `"${v.term}" (${v.translation})`).join(", ")}. After all three, guide the learner to say the phrase: "${mainPhrase.text}" (${mainPhrase.translation}). Teach ONLY these words. Never add synonyms, extra vocabulary, or words from other languages. One word at a time, one or two sentences per turn.`,
      openingLine: seed.openingLine,
      correctionStyle:
        "Cheer the effort first, gently fix just one word or sound, then invite them to try it again.",
      targetPhrases: [
        mainVocabulary.term,
        mainPhrase.text,
        ...seed.vocabulary.slice(1, 3).map((item) => item.term),
      ],
    },
  };
}
